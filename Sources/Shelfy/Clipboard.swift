import AppKit

/// Subtle sound + trackpad haptic when something lands on a shelf.
enum Feedback {
    private static var sound: NSSound?

    /// Plays the sound chosen in Settings at the chosen volume.
    private static func playSound() {
        let settings = Settings.shared
        if sound?.name != settings.dropSound { sound = NSSound(named: settings.dropSound) }
        sound?.stop()
        sound?.volume = Float(settings.dropVolume)
        sound?.play()
    }

    /// Settings preview, regardless of the on/off switch.
    static func preview() { playSound() }

    /// A drag arrived over a drop target. The haptic is only felt while the finger is still on the
    /// trackpad, so it fires here rather than on drop.
    static func enter() {
        guard Settings.shared.dropFeedback else { return }
        NSHapticFeedbackManager.defaultPerformer.perform(.levelChange, performanceTime: .now)
    }

    /// Items were dropped: play the sound right away.
    static func drop() {
        guard Settings.shared.dropFeedback else { return }
        NSHapticFeedbackManager.defaultPerformer.perform(.alignment, performanceTime: .now)
        playSound()
    }

    static func tick() {
        NSHapticFeedbackManager.defaultPerformer.perform(.alignment, performanceTime: .now)
    }
}

/// Polls the general pasteboard and records new copies on the Clipboard shelf.
final class ClipboardWatcher {
    /// Change count of Shelfy's own writes, so copying from a shelf isn't recorded again.
    static var ownChangeCount: Int?

    /// Types that password managers and other apps use to mark private or throwaway clipboard content.
    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount

    func start() {
        lastCount = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        timer?.tolerance = 0.2
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        guard Settings.shared.clipboardHistory, pb.changeCount != Self.ownChangeCount else { return }
        if let types = pb.types?.map(\.rawValue), types.contains(where: Self.skippedTypes.contains) { return }
        PB.read(pb) { items in ShelfStore.shared.clipboardShelf.recordClipboard(items) }
    }
}
